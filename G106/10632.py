res=[]
for _ in range(int(input())):
    d=list(map(int,input().replace(" ","").split(",")))
    rank=dict()
    do=d.copy()
    do.sort()
    for rs in range(len(d)):
        rank[do[rs]]=rs+1
    a=[]
    for rs in range(len(d)):
        a.append(str(rank[d[rs]]))
    res.append(", ".join(a))

for rs in res:
    print(rs)
